import { readFile } from 'node:fs/promises'
import { stripTypeScriptTypes } from 'node:module'

// Resolve Vite's extension-free imports in memory; never load the browser's env
// or instantiate the shared Supabase client in offline API/database tests.
const sourceDirectory = new URL('../../src/lib/instructor/', import.meta.url)
const errorsUrl = new URL('errors.ts', sourceDirectory).href
const moduleUrl = source => `data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(source)).toString('base64')}`
const collectorUrl = moduleUrl((await readFile(new URL('page-collector.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl)))
const adaptersUrl = moduleUrl((await readFile(new URL('adapters.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl)))
const decodersUrl = moduleUrl((await readFile(new URL('decoders.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl)))
// titles.ts only re-exports the shared module, so load the shared source directly.
const titlesUrl = moduleUrl(await readFile(new URL('../../../supabase/functions/_shared/instructor-titles.ts', sourceDirectory), 'utf8'))
const profileUrl = moduleUrl((await readFile(new URL('profile.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./titles'", JSON.stringify(titlesUrl)))
const gradingPanelsUrl = moduleUrl((await readFile(new URL('grading-panels.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl)))
const apiUrl = moduleUrl((await readFile(new URL('api.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./grading-panels'", JSON.stringify(gradingPanelsUrl))
  .replaceAll("'./profile'", JSON.stringify(profileUrl))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./page-collector'", JSON.stringify(collectorUrl))
  .replaceAll("'./decoders'", JSON.stringify(decodersUrl))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl)))
const calendarViewUrl = moduleUrl((await readFile(new URL('calendar-view.ts', sourceDirectory), 'utf8'))
  .replaceAll("'../instructor-calendar'", JSON.stringify(new URL('../instructor-calendar.ts', sourceDirectory).href))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl)))
const calendarQueriesUrl = moduleUrl((await readFile(new URL('calendar-queries.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./page-collector'", JSON.stringify(collectorUrl))
  .replaceAll("'./calendar-view'", JSON.stringify(calendarViewUrl)))
const directoryUrl = moduleUrl((await readFile(new URL('directory.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./decoders'", JSON.stringify(decodersUrl))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl)))
const studentDetailUrl = moduleUrl((await readFile(new URL('student-detail.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl))
  .replaceAll("'./calendar-queries'", JSON.stringify(calendarQueriesUrl)))
const gradingUrl = moduleUrl((await readFile(new URL('grading.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl))
  .replaceAll("'./calendar-queries'", JSON.stringify(calendarQueriesUrl))
  .replaceAll("'./decoders'", JSON.stringify(decodersUrl))
  .replaceAll("'./directory'", JSON.stringify(directoryUrl))
  .replaceAll("'./student-detail'", JSON.stringify(studentDetailUrl)))
const sessionReadsUrl = moduleUrl((await readFile(new URL('session-reads.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl))
  .replaceAll("'./calendar-queries'", JSON.stringify(calendarQueriesUrl))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl))
  .replaceAll("'./student-detail'", JSON.stringify(studentDetailUrl)))
const attendanceUrl = moduleUrl((await readFile(new URL('attendance.ts', sourceDirectory), 'utf8'))
  .replaceAll("'./adapters'", JSON.stringify(adaptersUrl))
  .replaceAll("'./calendar-queries'", JSON.stringify(calendarQueriesUrl))
  .replaceAll("'./calendar-view'", JSON.stringify(calendarViewUrl))
  .replaceAll("'./errors'", JSON.stringify(errorsUrl)))

export const errors = await import(errorsUrl)
export const adapters = await import(adaptersUrl)
export const decoders = await import(decodersUrl)
export const api = await import(apiUrl)
export const profile = await import(profileUrl)
export const gradingPanels = await import(gradingPanelsUrl)
export const calendarView = await import(calendarViewUrl)
export const calendarQueries = await import(calendarQueriesUrl)
export const directory = await import(directoryUrl)
export const studentDetail = await import(studentDetailUrl)
export const grading = await import(gradingUrl)
export const sessionReads = await import(sessionReadsUrl)
export const attendance = await import(attendanceUrl)
export const sessionWrites = await import(new URL('session-writes.ts', sourceDirectory).href)
